"""SSH aliases for deployment-isolated OpenStack machines."""

from ipaddress import IPv4Address
import re


def address(server, deployment, floating=False):
    for network, addresses in server.addresses.items():
        if not network.startswith(deployment + "-"):
            continue
        for entry in addresses:
            if (entry.get("OS-EXT-IPS:type", "fixed") == ("floating" if floating else "fixed")):
                try:
                    return str(IPv4Address(entry["addr"]))
                except (KeyError, ValueError):
                    continue
    return None


def write_ssh_config(conn, deployments, path):
    servers = list(conn.compute.servers())
    lines = ["# Generated by attackbed; use ssh -F this-file HOST", ""]
    for deployment in deployments:
        machines = sorted((server for server in servers if server.name.startswith(deployment + "-")),
                          key=lambda server: server.name)
        management = next((server for server in machines if server.name == deployment + "-mgmt"), None)
        if not management:
            raise ValueError(f"Missing management VM for {deployment}")
        public_ip = address(management, deployment, floating=True)
        if not public_ip:
            public_ip = next((ip.floating_ip_address for ip in conn.network.ips()
                              if ip.description == deployment + "-mgmt" and ip.port_id), None)
        if not public_ip:
            raise ValueError(f"Missing management floating IP for {deployment}")
        lines.extend([f"Host {deployment}-mgmt", f"    HostName {IPv4Address(public_ip)}",
                      "    User ubuntu", ""])
        for server in machines:
            if server.name == management.name:
                continue
            if not re.fullmatch(r"[a-z0-9-]+", server.name):
                raise ValueError(f"Invalid SSH host name: {server.name!r}")
            private_ip = address(server, deployment)
            if not private_ip:
                raise ValueError(f"Missing private IP for {server.name}")
            role = server.name[len(deployment) + 1:]
            user = "debian" if role in ("videoserver", "linuxshare") else "ubuntu"
            lines.extend([f"Host {server.name}", f"    HostName {private_ip}",
                          f"    User {user}", f"    ProxyJump {deployment}-mgmt",
                          f"    HostKeyAlias {server.name}", ""])
    path.write_text("\n".join(lines))
    path.chmod(0o600)
